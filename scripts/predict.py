"""Score validation.csv and the December chart inputs with the trained model.

Run:  python scripts/predict.py
Writes validation_predictions.csv, fills data/december_chart_inputs.csv in place and writes
reports/prediction_checks.md (input coverage and prediction sanity checks).
"""
from __future__ import annotations

import pickle
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np
import pandas as pd

from freight import config, data


def check(pred: np.ndarray, label: str) -> None:
    if not np.isfinite(pred).all() or (pred <= 0).any():
        raise SystemExit(f"{label}: non-finite or non-positive predictions")


def write_checks(val: pd.DataFrame, pred: np.ndarray, december: pd.DataFrame, model) -> None:
    train = data.flag_label_outliers(data.load_train())
    train = train[train["label_outlier"] == 0]
    train_cities = set(train["pickup"]) | set(train["delivery"])
    train_lanes = set(train["pickup"] + ">" + train["delivery"])
    lanes = val["pickup"] + ">" + val["delivery"]
    q = [0.01, 0.25, 0.5, 0.75, 0.99]

    lines = ["# Prediction checks (auto-generated by scripts/predict.py)", "",
             "## Validation inputs", "", "| Check | Value |", "|---|---|",
             f"| rows | {len(val):,} |",
             f"| dates | {val['date'].min().date()} to {val['date'].max().date()} |",
             f"| loads on a lane seen in training | {lanes.isin(train_lanes).mean():.1%} |",
             f"| loads on a lane with a learned premium | {lanes.isin(model.premium.index).mean():.1%} |",
             f"| loads touching a city unseen in training | "
             f"{(~val['pickup'].isin(train_cities) | ~val['delivery'].isin(train_cities)).mean():.1%} |",
             f"| missing weight (filled) | {val['weight'].isna().sum()} |",
             f"| negative weight (sign-flipped) | {(val['weight'] < 0).sum()} |",
             f"| missing market_index (filled with day mean) | {val['market_index'].isna().sum()} |",
             "", "## Predictions", "", "| Check | Value |", "|---|---|",
             f"| missing / non-finite | {int((~np.isfinite(pred)).sum())} |",
             f"| non-positive | {int((pred <= 0).sum())} |",
             "", "| Quantile | Predicted rate | Training rate (clean) | Predicted $/mile | Training $/mile |",
             "|---|---|---|---|---|"]
    pred_rpm, train_rpm = pred / val["distance"], train[config.TARGET] / train["distance"]
    for x in q:
        lines.append(f"| P{int(x * 100):02d} | ${np.quantile(pred, x):,.0f} | ${train[config.TARGET].quantile(x):,.0f} | "
                     f"${np.quantile(pred_rpm, x):.2f} | ${train_rpm.quantile(x):.2f} |")
    by_eq = pd.DataFrame({"eq": val["equipment"], "rpm": pred_rpm}).groupby("eq")["rpm"].median()
    train_eq = train_rpm.groupby(train["equipment"]).median()
    lines += ["", "| Equipment | Predicted median $/mile (Nov-Dec) | Training median $/mile (Jan-Oct) |", "|---|---|---|"]
    lines += [f"| {e} | ${by_eq[e]:.2f} | ${train_eq[e]:.2f} |" for e in config.EQUIPMENT_TYPES]
    shift = np.median(pred_rpm) / train_rpm.median() - 1
    lines += ["", f"Median predicted $/mile is {shift:+.1%} vs training. The lower Nov-Dec market index "
              f"({val['market_index'].mean():.2f} vs {train['market_index'].mean():.2f}) pulls prices down; the "
              "underlying monthly drift and the December quarter-end ramp push them up.", "",
              "## December chart", "",
              f"31 rows, ${december['predicted_rate'].min():,.2f} to ${december['predicted_rate'].max():,.2f} "
              f"(Dec 1 ${december['predicted_rate'].iloc[0]:,.2f}, Dec 31 ${december['predicted_rate'].iloc[-1]:,.2f}).", ""]
    report = "\n".join(lines)
    (config.REPORTS_DIR / "prediction_checks.md").write_text(report, encoding="utf-8")
    print(report)


def main() -> None:
    with open(config.ARTIFACTS_DIR / "model.pkl", "rb") as fh:
        bundle = pickle.load(fh)
    builder, model = bundle["builder"], bundle["model"]

    val = data.load_validation()
    val_pred = model.predict(builder.transform(val))
    check(val_pred, "validation")
    template = pd.read_csv(config.TEMPLATE_PATH)
    by_id = pd.Series(val_pred, index=val["load_id"])
    if set(template["load_id"]) != set(by_id.index):
        raise SystemExit("template load_ids do not match validation.csv")
    template["predicted_rate"] = template["load_id"].map(by_id).round(2)
    template[["load_id", "predicted_rate"]].to_csv(config.PREDICTIONS_PATH, index=False)
    print(f"Wrote {len(template):,} predictions -> {config.PREDICTIONS_PATH.name} "
          f"(median ${template.predicted_rate.median():,.0f})")

    december = pd.read_csv(config.DECEMBER_PATH)
    columns = list(december.columns)
    dec_pred = model.predict(builder.transform(december.assign(date=pd.to_datetime(december["date"]))))
    check(dec_pred, "december")
    december["predicted_rate"] = np.round(dec_pred, 2)
    december[columns].to_csv(config.DECEMBER_PATH, index=False)
    print(f"Filled {len(december)} December rows -> {config.DECEMBER_PATH.relative_to(config.ROOT)}")
    write_checks(val, val_pred, december, model)


if __name__ == "__main__":
    main()
