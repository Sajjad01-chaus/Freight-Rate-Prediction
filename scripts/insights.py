"""Accuracy bands, prediction intervals and business numbers for the final model.

Run:  python scripts/insights.py
Writes reports/insights.md and reports/figures/08_*.png, 09_*.png
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pickle

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from freight import config, data
from freight.evaluation import FOLDS
from freight.features import FeatureBuilder
from freight.models import final_model

BLUE, ORANGE, AQUA, INK_2 = "#2a78d6", "#eb6834", "#1baf7a", "#52514e"
plt.rcParams.update({
    "figure.dpi": 150, "savefig.dpi": 150, "savefig.bbox": "tight", "font.size": 10,
    "axes.titlesize": 12, "axes.titleweight": "bold", "axes.titlelocation": "left",
    "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True,
    "grid.color": "#e4e3df", "axes.axisbelow": True, "legend.frameon": False,
})


def out_of_fold_residuals(train, X, y, clean) -> pd.DataFrame:
    parts = []
    for fold in FOLDS:
        tr, te = fold.split(train)
        model = final_model().fit(X[tr & clean], y[tr & clean])
        te = te & clean
        parts.append(pd.DataFrame({
            "fold": fold.name, "date": train.loc[te, "date"], "equipment": train.loc[te, "equipment"],
            "y": y[te], "pred": model.predict(X[te]),
        }))
        print(f"  {fold.name} done", flush=True)
    res = pd.concat(parts)
    res["log_err"] = np.log(res["y"] / res["pred"])
    return res


def main() -> None:
    train = data.flag_label_outliers(data.load_train())
    val = data.load_validation()
    builder = FeatureBuilder().fit(train, val)
    X, y = builder.transform(train), train[config.TARGET]
    clean = train["label_outlier"].eq(0)

    print("Fitting final model on each fold...")
    res = out_of_fold_residuals(train, X, y, clean)
    abs_pct = np.abs(res["pred"] / res["y"] - 1)
    lines = ["# Accuracy, uncertainty and business insights (auto-generated by scripts/insights.py)", ""]

    lines += ["## How close are the predictions? (all 4 time folds, clean labels)", "",
              "| Within | Share of loads |", "|---|---|"]
    for t in (0.01, 0.02, 0.03, 0.05, 0.10):
        lines.append(f"| {t:.0%} | {(abs_pct <= t).mean():.1%} |")
    abs_dollar = (res["pred"] - res["y"]).abs()
    lines += ["", f"Median absolute error ${abs_dollar.median():.0f}, mean ${abs_dollar.mean():.0f} "
              f"(median load ${res['y'].median():,.0f}).", ""]

    # 90% interval: calibrate quantiles on the production-like folds, check on the others
    calib = res["fold"].str.startswith("Q")
    lo, hi = np.quantile(res.loc[calib, "log_err"], [0.05, 0.95])
    inside = (res["log_err"] >= lo) & (res["log_err"] <= hi)
    lines += ["## 90% price range", "",
              f"Band: prediction x [{np.exp(lo):.3f}, {np.exp(hi):.3f}] "
              f"(i.e. {np.expm1(lo):+.1%} / {np.expm1(hi):+.1%}), quantiles taken from folds Q2+Q3.", "",
              "| Fold | Coverage |", "|---|---|"]
    for name, grp in inside.groupby(res["fold"]):
        lines.append(f"| {name} | {grp.mean():.1%} |")
    lines.append("")

    # business numbers from the final model's market component
    with open(config.ARTIFACTS_DIR / "model.pkl", "rb") as fh:
        model = pickle.load(fh)["model"]
    coef = model.base.linear.coef
    ramp = {"Dry Van": coef["qe_ramp"], "Flatbed": coef["qe_ramp"] + coef["qe_ramp_flatbed"],
            "Reefer": coef["qe_ramp"] + coef["qe_ramp_reefer"]}
    market_elasticity = coef["log_market_index"] + coef["log_market_index_day"]
    typical = train.loc[clean].groupby("equipment")[config.TARGET].median()

    lines += ["## Business numbers", "",
              "| Equipment | Quarter-end uplift (last day) | On a median load |", "|---|---|---|"]
    for eq, c in ramp.items():
        lines.append(f"| {eq} | {np.expm1(c):+.1%} | ${typical[eq] * np.expm1(c):,.0f} (median ${typical[eq]:,.0f}) |")
    lines += ["",
              f"- Market sensitivity: a 10% rise in the market index lifts rates by {1.1 ** market_elasticity - 1:.1%}.",
              f"- Underlying drift: {np.expm1(coef['trend_months']):+.2%} per month after market and calendar effects.",
              f"- Lane premiums (after shrinkage): {model.premium.size:,} lanes, "
              f"range {np.expm1(model.premium.min()):+.1%} to {np.expm1(model.premium.max()):+.1%}.",
              f"- Corrupted labels caught: {int((~clean).sum())} of {len(train):,} ({(~clean).mean():.2%}).", ""]
    (config.REPORTS_DIR / "insights.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))

    # figure: accuracy bands
    fig, ax = plt.subplots(figsize=(8, 3.4))
    bins = np.linspace(-0.08, 0.08, 81)
    ax.hist(np.expm1(-res["log_err"]), bins=bins, color=BLUE)
    for x in (np.expm1(-hi), np.expm1(-lo)):
        ax.axvline(x, color=INK_2, linewidth=0.8)
    ax.set_xticks([-0.06, -0.03, 0, 0.03, 0.06]); ax.set_xticklabels(["-6%", "-3%", "0", "+3%", "+6%"])
    ax.set_xlabel("Prediction error (predicted / actual - 1), unseen months")
    ax.set_ylabel("Loads")
    ax.set_title(f"{(abs_pct <= 0.03).mean():.0%} of loads priced within 3%; lines mark the 90% range")
    fig.savefig(config.FIGURES_DIR / "08_error_distribution.png"); plt.close(fig)

    # figure: quarter-end ramp by equipment, as the model applies it
    days = np.arange(60, -1, -1)
    ramp_feature = np.clip(1 - days / 31.0, 0, 1)
    fig, ax = plt.subplots(figsize=(8, 3.4))
    for (eq, c), color in zip(ramp.items(), (BLUE, ORANGE, AQUA)):
        ax.plot(-days, np.expm1(c * ramp_feature) * 100, color=color, label=eq)
    ax.set_xlabel("Days to quarter end"); ax.set_ylabel("Rate uplift (%)")
    ax.set_xticks([-60, -45, -30, -15, 0]); ax.set_xticklabels(["60", "45", "30", "15", "0"])
    ax.set_title("Quarter-end uplift learned by the model (applies to Dec 2025)")
    ax.legend(loc="upper left")
    fig.savefig(config.FIGURES_DIR / "09_quarter_end_uplift.png"); plt.close(fig)


if __name__ == "__main__":
    main()
